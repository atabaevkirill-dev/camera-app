def set_lang(lang: str) -> None:
    global _lang
    _lang = "en" if str(lang).lower().startswith("en") else "ru"


def get_lang() -> str:
    return _lang


def tr(key: str, **kwargs) -> str:
    entry = TR.get(key)
    if not entry:
        return key
    text = entry.get(_lang) or entry.get("ru") or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text